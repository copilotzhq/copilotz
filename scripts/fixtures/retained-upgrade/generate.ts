/**
 * Generate the retained fixture with the actual pre-conversion checkout.
 * Run with its deno.json, not this release's import map:
 * deno run -A --config OLD/deno.json generate.ts OLD OUTPUT.json
 * COPILOTZ_TEST_POSTGRES_URL must name a disposable local test database.
 */
import type {
  SqlExecutor,
  SqlSession,
} from "../../../runtime/events/session.ts";

const [checkout, output] = Deno.args;
if (!checkout || !output) {
  throw new Error("Expected old checkout and output path.");
}
const revision = "8736b9c8b86f09b8febf3e2510f904ebfd2be28c";
const verified = await new Deno.Command("git", {
  args: ["-C", checkout, "rev-parse", "HEAD"],
  stdout: "piped",
}).output();
if (new TextDecoder().decode(verified.stdout).trim() !== revision) {
  throw new Error(
    "Fixture must be generated by the exact pre-conversion revision.",
  );
}
const load = (path: string) =>
  import(new URL(path, `file://${checkout}/`).href);
const { createTestDatabase } = await load("runtime/testing/ominipg.ts");
const { createCopilotz: createCopilotzApplication } = await load(
  "create-copilotz.ts",
);
const { defineAction } = await load("runtime/actions/define.ts");
const { definePlugin } = await load("runtime/plugins/index.ts");
const { defineCollection } = await load("runtime/collections/index.ts");
const { createEventStore } = await load("runtime/events/index.ts");
const { createOperationCatalog } = await load("runtime/streams/catalog.ts");
const { createStreamOutputDescriptor } = await load(
  "runtime/streams/observation.ts",
);
const { createDatabaseBodyStore } = await load(
  "runtime/content/database-body-store.ts",
);
const url = Deno.env.get("COPILOTZ_TEST_POSTGRES_URL");
if (!url) throw new Error("A disposable local PostgreSQL URL is required.");
const database = await createTestDatabase({ url });
const schema = "retained_upgrade_fixture";
const statements: string[] = [];
const wrap = (executor: SqlExecutor): SqlExecutor => ({
  async query(sql, params) {
    const result = await executor.query(sql, params);
    if (/^\s*(CREATE|ALTER|DROP\s+TRIGGER)/i.test(sql)) {
      if (params?.length) {
        throw new Error("Parameterized fixture DDL needs explicit encoding.");
      }
      statements.push(sql);
    }
    return result as never;
  },
});
const session: SqlSession = {
  query: wrap(database).query,
  transaction: (run) =>
    database.transaction((tx: SqlExecutor) => run(wrap(tx))),
};
let calls = 0;
const plugin = definePlugin({
  id: "upgrade.fixture",
  version: "1",
  collections: {
    documents: defineCollection({
      name: "upgrade_document",
      schema: {
        type: "object",
        properties: { id: { type: "string" }, content: { type: "array" } },
        required: ["id", "content"],
      },
      content: { fields: ["content"] },
    }),
  },
  actions: {
    capture: defineAction({
      id: "upgrade.capture",
      execute: (input: unknown) => input,
    }),
    prepareParent: defineAction({
      id: "upgrade.prepare-parent",
      execute(
        _input: unknown,
        context: {
          actions: {
            capture: {
              prepare: (
                factory: () => unknown,
                options: { operationKey: string },
              ) => Promise<unknown>;
            };
          };
        },
      ) {
        return context.actions.capture.prepare(
          () => ({
            input: { value: "original captured input" },
            metadata: { revision: 1 },
          }),
          { operationKey: "retained-capture" },
        );
      },
    }),
    echo: defineAction({
      id: "upgrade.echo",
      content: { input: ["content"] },
      execute(input: unknown) {
        calls++;
        return { accepted: Boolean(input), original: true };
      },
    }),
  },
});
try {
  const app = await createCopilotzApplication({
    database: { ...session, close: () => Promise.resolve() },
    namespace: "archive",
    databaseSchema: schema,
    plugins: [plugin],
  });
  const bytes = "retained original content";
  const input = { content: [bytes] };
  try {
    const document = await app.collections.documents.create({
      id: "document-retained",
      ...input,
    }, { idempotencyKey: "document-retained" });
    await app.actions.echo({ content: document.content }, {
      idempotencyKey: "retained-echo",
    });
    await app.actions.echo({ content: document.content }, {
      idempotencyKey: "retained-echo",
    });
    await app.actions.prepareParent({}, {
      idempotencyKey: "retained-preparation",
    });
    if (calls !== 1) {
      throw new Error("Old runtime did not retain idempotent Action history.");
    }
  } finally {
    await app.close();
  }
  const store = createEventStore({ session, schema });
  const catalog = createOperationCatalog(session, schema);
  const bodies = createDatabaseBodyStore({ session, schema });
  for (
    const [index, outcome] of [
      "completed",
      "superseded",
      "abandoned",
      "missing",
      "purge_pending",
    ].entries()
  ) {
    const namespace = index % 2 ? "archive-secondary" : "archive";
    const root = await store.append({
      type: "upgrade.stream",
      namespace,
      payload: { outcome },
      deduplicationId: `stream-${outcome}`,
    }, []);
    await session.transaction((tx) =>
      catalog.indexEvent(tx, {
        namespace,
        operationId: root.event.id,
        eventId: root.event.id,
        position: root.event.position,
        correlationId: root.event.id,
        createdAt: root.event.createdAt,
        metadata: {},
      })
    );
    const streamId = `stream-${outcome}`, bodyId = `retained-${outcome}`;
    await catalog.openStream({
      namespace,
      operationId: root.event.id,
      semanticStreamId: streamId,
      bodyId,
      descriptor: createStreamOutputDescriptor({
        id: streamId,
        semanticId: streamId,
        mediaType: "text/plain",
        kind: "text",
        role: "body",
        metadata: {},
      }, { namespace }),
    });
    if (outcome === "missing") {
      await catalog.markStreamUnavailable({
        namespace,
        operationId: root.event.id,
        streamId,
        outcome: "failed",
        availability: "missing",
      });
    } else {
      const writer = await bodies.reserve({ bodyId, mediaType: "text/plain" });
      const chunk = new TextEncoder().encode(`retained ${outcome}`);
      await bodies.append({
        writer,
        expectedOffset: 0,
        appendId: "part-1",
        bytes: chunk,
      });
      await catalog.commitStreamOffset({
        namespace,
        operationId: root.event.id,
        streamId,
        committedOffset: chunk.length,
      });
      if (outcome === "completed" || outcome === "purge_pending") {
        const body = await bodies.seal({
          writer,
          expectedByteLength: chunk.length,
        });
        await catalog.sealStream({
          namespace,
          operationId: root.event.id,
          streamId,
          body,
        });
      } else {
        const body = await bodies.terminate({
          writer,
          expectedByteLength: chunk.length,
        });
        await catalog.terminateStream({
          namespace,
          operationId: root.event.id,
          streamId,
          outcome,
          body,
        });
      }
      if (outcome === "purge_pending") {
        await catalog.markStreamPurgePending({
          namespace,
          operationId: root.event.id,
          streamId,
        });
      }
    }
    await catalog.reconcile({ namespace, operationId: root.event.id });
  }
  // An allocated but rolled-back position makes gap-free seq backfill observable.
  try {
    await session.transaction(async (tx) => {
      await tx.query(`SELECT nextval('"${schema}".events_position_seq')`);
      throw new Error("fixture rollback");
    });
  } catch { /* intentional */ }
  await store.append({
    type: "upgrade.after-gap",
    namespace: "archive",
    payload: {},
    deduplicationId: "after-gap",
  }, []);
  const tables = [
    "nodes",
    "edges",
    "events",
    "event_bodies",
    "event_deliveries",
    "open_actions",
    "copilotz_schema_metadata",
    "copilotz_operation_catalog_metadata",
    "copilotz_operations",
    "copilotz_operation_events",
    "copilotz_operation_selection_heads",
    "copilotz_operation_selections",
    "copilotz_operation_streams",
    "content_bodies",
    "content_body_parts",
  ];
  const rows: Record<string, unknown[]> = {};
  const actual = (await database.query(
    "SELECT tablename FROM pg_tables WHERE schemaname=$1",
    [schema],
  )).rows.map((row: { tablename: string }) => row.tablename);
  for (const table of actual) if (!tables.includes(table)) tables.push(table);
  for (const table of tables) {
    if (!actual.includes(table)) continue;
    rows[table] = (await database.query(
      `SELECT row_to_json(t) AS row FROM "${schema}"."${table}" AS t`,
    )).rows.map((row: { row: unknown }) => row.row);
  }
  await Deno.writeTextFile(
    output,
    JSON.stringify({ revision, schema, statements, rows }, null, 2) + "\n",
  );
  console.log(
    JSON.stringify({
      revision,
      statements: statements.length,
      rows: Object.fromEntries(
        Object.entries(rows).map(([name, values]) => [name, values.length]),
      ),
    }),
  );
} finally {
  await database.query(`DROP SCHEMA IF EXISTS "${schema}" CASCADE`);
  await database.close();
}
